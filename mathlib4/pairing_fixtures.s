.section .pairing_defs,"a",@progbits
    .ascii "local notation \"ℕ\" => Nat\n"
    .ascii "namespace Nat\n"
    .ascii "def sqrt (n : Nat) : Nat :=\n"
    .ascii "  if n ≤ 1 then n else\n"
    .ascii "  iter n (n / 2)\n"
    .ascii "where\n"
    .ascii "  @[semireducible] iter (n guess : Nat) : Nat :=\n"
    .ascii "    let next := (guess + n / guess) / 2\n"
    .ascii "    if _h : next < guess then\n"
    .ascii "      iter n next\n"
    .ascii "    else\n"
    .ascii "      guess\n"
    .ascii "  termination_by guess\n"
    .ascii "\n"
    .ascii "def pair (a b : ℕ) : ℕ :=\n"
    .ascii "  if a < b then b * b + a else a * a + a + b\n"
    .ascii "\n"
    .ascii "def unpair (n : ℕ) : ℕ × ℕ :=\n"
    .ascii "  let s := sqrt n\n"
    .ascii "  if n - s * s < s then (n - s * s, s) else (s, n - s * s - s)\n"
    .ascii "end Nat\n"

.section .pairing_main,"a",@progbits
    .ascii "\n"
    .ascii "def main (paths : List String) : IO Unit := do\n"
    .ascii "  let [path] := paths | throw (IO.userError \"expected case file\")\n"
    .ascii "  for line in ← IO.FS.lines path do\n"
    .ascii "    match line.splitOn \" \" with\n"
    .ascii "    | [\"pair\", a, b] => IO.println (Nat.pair a.toNat! b.toNat!)\n"
    .ascii "    | [\"unpair\", n] =>\n"
    .ascii "      let (a, b) := Nat.unpair n.toNat!\n"
    .ascii "      IO.println (toString a ++ \" \" ++ toString b)\n"
    .ascii "    | _ => throw (IO.userError \"invalid case\")\n"

